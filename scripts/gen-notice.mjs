// Regenerates NOTICE: every third-party package shipped in the app binary, with its license.
// Usage: node scripts/gen-notice.mjs  (needs `cargo` and an installed node_modules).
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";

const rust = execFileSync(
  "cargo",
  ["tree", "--manifest-path", "src-tauri/Cargo.toml", "-e", "normal", "--prefix", "none", "--format", "{p}\t{l}"],
  { encoding: "utf8" },
)
  .split("\n")
  .map((l) => l.replace(/ \((\*|proc-macro|[^)]*src-tauri)\)/g, "").trim())
  .filter((l) => l && !l.startsWith("lumio-ng-app"));

// Production npm packages only (what Vite bundles into the webview), from the lockfile.
const lock = JSON.parse(readFileSync("package-lock.json", "utf8"));
const npm = Object.entries(lock.packages)
  .filter(([path, p]) => path.startsWith("node_modules/") && !p.dev)
  .map(([path, p]) => `${path.slice(path.lastIndexOf("node_modules/") + 13)} v${p.version}\t${p.license ?? "see package"}`);

const block = (rows) => [...new Set(rows)].sort((a, b) => a.localeCompare(b)).map((r) => r.replace("\t", "  —  ")).join("\n");

writeFileSync(
  "NOTICE",
  `LumioNG
Copyright (C) 2025-2026 NG and LumioNG contributors
Licensed under the GNU AGPL v3.0 only (see LICENSE and LICENSING.md).

This product includes third-party software. Each component remains under its own license, listed
below as "name version  —  SPDX license expression". Full license texts ship with each package's
source (crates.io / npm). Generated by scripts/gen-notice.mjs; do not edit by hand.

== Rust crates (src-tauri) ==
${block(rust)}

== JavaScript packages (bundled frontend) ==
${block(npm)}
`,
);
console.log(`NOTICE: ${new Set(rust).size} crates, ${new Set(npm).size} npm packages`);
